package filmgrain

// Params is the subset of film_grain_params this package currently
// consumes. The real spec structure (§5.9.30) carries more detail — AR
// coefficients, chroma scaling flags, overlap/clipping switches. We
// start with the fields needed for the RNG + scaling + naive tiling
// path; follow-up phases fill the rest in.
type Params struct {
	// GrainSeed mixes into the per-position RNG seed. Zero disables
	// grain application (spec §7.20.1).
	GrainSeed uint16

	// ScalingY is the piecewise-linear scaling LUT for the luma plane.
	ScalingY ScalingLUT

	// ScalingU / ScalingV scale the chroma planes. Callers that want
	// luma-only grain can leave these as zero LUTs.
	ScalingU ScalingLUT
	ScalingV ScalingLUT

	// ScalingShift right-shifts the product (grain * scale) before it
	// is added to the pixel. Spec allows 8..11; the default 8 leaves
	// the grain at full amplitude.
	ScalingShift uint8

	// ClipToRestrictedRange clamps the output to broadcast-legal range
	// [16, 235] for luma and [16, 240] for chroma, mirroring libaom's
	// clip_to_restricted_range.
	ClipToRestrictedRange bool
}

// clampByte clamps v to [0, 255] for 8-bit output.
func clampByte(v int) uint8 {
	if v < 0 {
		return 0
	}
	if v > 255 {
		return 255
	}
	return uint8(v)
}

// ApplyGrainPlane adds scaled grain to an 8-bit plane. plane is laid out
// row-major of size w*h; stride is the distance between rows (in
// samples, not bytes). scaling is the LUT to use for this plane; set it
// to a zero LUT to disable grain on the plane.
//
// The grain is generated by a per-position RNG seeded with
// (grainSeed ^ row_offset ^ column_offset). This is a simplification of
// the spec's block-based grain pattern reuse — it produces noise with
// the right amplitude but without the 32×32 tiling the spec mandates.
// The full tiler is a follow-up.
func ApplyGrainPlane(plane []uint8, w, h, stride int, scaling *ScalingLUT, p *Params) {
	if p == nil || p.GrainSeed == 0 {
		return
	}
	shift := p.ScalingShift
	if shift == 0 {
		shift = 8
	}
	loY, hiY := 0, 255
	if p.ClipToRestrictedRange {
		loY, hiY = 16, 235
	}
	rng := NewRNG(0)
	for y := 0; y < h; y++ {
		row := plane[y*stride : y*stride+w]
		for x := 0; x < w; x++ {
			seed := p.GrainSeed ^ uint16(y<<8) ^ uint16(x)
			if seed == 0 {
				seed = 1
			}
			rng.Seed(seed)
			// Advance once so the seed itself is never returned
			// verbatim as the grain byte.
			rng.Next()
			grain := rng.Byte() // signed, [-128, 127]
			scale := int(scaling.Lookup(row[x]))
			delta := (grain * scale) >> uint(shift)
			v := int(row[x]) + delta
			if v < loY {
				v = loY
			}
			if v > hiY {
				v = hiY
			}
			row[x] = uint8(v)
		}
	}
}

// Apply runs film grain synthesis on all three planes using the per-
// plane LUTs from p. U/V must be non-nil for chroma to be touched; pass
// nil to skip them.
//
// strideY / strideC are the plane strides; yw/yh and cw/ch describe the
// luma and chroma dimensions respectively. Clipping to restricted range
// uses [16, 240] on chroma when requested.
func Apply(y []uint8, yw, yh, strideY int,
	u, v []uint8, cw, ch, strideC int,
	p *Params) {
	if p == nil || p.GrainSeed == 0 {
		return
	}
	ApplyGrainPlane(y, yw, yh, strideY, &p.ScalingY, p)
	if u != nil {
		applyChroma(u, cw, ch, strideC, &p.ScalingU, p)
	}
	if v != nil {
		applyChroma(v, cw, ch, strideC, &p.ScalingV, p)
	}
}

func applyChroma(plane []uint8, w, h, stride int, scaling *ScalingLUT, p *Params) {
	// Same code path as luma but with chroma restricted range.
	shift := p.ScalingShift
	if shift == 0 {
		shift = 8
	}
	lo, hi := 0, 255
	if p.ClipToRestrictedRange {
		lo, hi = 16, 240
	}
	rng := NewRNG(0)
	for y := 0; y < h; y++ {
		row := plane[y*stride : y*stride+w]
		for x := 0; x < w; x++ {
			seed := p.GrainSeed ^ uint16(y<<8) ^ uint16(x) ^ 0x2A2A
			if seed == 0 {
				seed = 1
			}
			rng.Seed(seed)
			rng.Next()
			grain := rng.Byte()
			scale := int(scaling.Lookup(row[x]))
			delta := (grain * scale) >> uint(shift)
			val := int(row[x]) + delta
			if val < lo {
				val = lo
			}
			if val > hi {
				val = hi
			}
			row[x] = uint8(val)
		}
	}
}
